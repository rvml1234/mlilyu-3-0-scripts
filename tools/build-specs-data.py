#!/usr/bin/env python3
"""Builds find-specs/mattress/<slug>.js from find-specs/specs-data.js.

The Find Specs page loads the whole catalog. The modal on a mattress page loads only that mattress, so it stays light.
Run this again after changing specs-data.js:

    python3 tools/build-specs-data.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "find-specs"
SLUGS = {"powercool": "powercool-pro"}   # the data's id where it differs from the page's address
FIELDS = ("feel", "size", "sku", "upc", "part", "msrp", "dims", "box", "weight", "notes")

source = (ROOT / "specs-data.js").read_text(encoding="utf8")
data = json.loads(source[source.index("{") : source.rindex("}") + 1])
products = {}
for row in next(c for c in data["categories"] if c["id"] == "mattress")["rows"]:
    if row.get("product"):
        products.setdefault(row["product"], []).append(row)

(ROOT / "mattress").mkdir(exist_ok=True)
order = data["sizeOrder"]
for product, rows in products.items():
    slug = SLUGS.get(product, product)
    rows.sort(key=lambda r: order.index(r["size"]) if r.get("size") in order else 99)
    out = {
        "name": rows[0]["name"],
        "slug": slug,
        "source": data["source"],
        "msrpSource": data["msrpSource"],
        "rows": [{k: r[k] for k in FIELDS if r.get(k) not in (None, "", [])} for r in rows],
    }
    text = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
    (ROOT / "mattress" / (slug + ".js")).write_text(
        "/* Find Specs for one mattress. GENERATED by tools/build-specs-data.py from find-specs/specs-data.js. */\n"
        "window.MLILY_MATTRESS_SPECS=" + text + ";\n",
        encoding="utf8",
    )
    print(slug, len(rows), "rows")
