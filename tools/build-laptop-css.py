#!/usr/bin/env python3
"""Builds pdp/pdp-laptop.css from the published Mattresses template.

The prototype switches to its tablet layout at 1100 px. Webflow's first breakpoint is 991 px, so the template's own
tablet rules are copied, unchanged, into a 992-1100 px media query. Run this again after changing tablet styles in Webflow:

    python3 tools/build-laptop-css.py
"""
import re
import urllib.request
from pathlib import Path

PAGE = "https://mlily-u-3-0.webflow.io/mattresses/midnight-ice"
OUT = Path(__file__).resolve().parent.parent / "pdp" / "pdp-laptop.css"
TABLET = "@media screen and (max-width:991px)"


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    return urllib.request.urlopen(request).read().decode("utf8")


def block_after(css, start):
    """The text inside the { } that opens after start."""
    opened = css.index("{", start)
    depth, i = 1, opened + 1
    while depth:
        depth += {"{": 1, "}": -1}.get(css[i], 0)
        i += 1
    return css[opened + 1 : i - 1]


html = fetch(PAGE)
css_url = re.search(r'href="([^"]+webflow[^"]+\.css)"', html).group(1)
css = re.sub(r"\s*([{}:;,])\s*", r"\1", fetch(css_url))
page_classes = {name for attr in re.findall(r'class="([^"]+)"', html) for name in attr.split()}

rules = []
for match in re.finditer(re.escape(TABLET), css):
    for selector, body in re.findall(r"([^{}]+)\{([^{}]*)\}", block_after(css, match.start())):
        kept = []
        for part in selector.split(","):
            classes = re.findall(r"\.([\w-]+)", part)
            usable = classes and all(c in page_classes for c in classes)
            # the top bar stays at its desktop size up to 1100 px, so its rules and the page's offset under it stay out
            if usable and "pdp-page" not in classes and not any(c.startswith(("w-", "sh-")) for c in classes):
                kept.append(part.strip())
        if kept:
            rules.append("  %s { %s }" % (", ".join(kept), body.strip().rstrip(";") + ";"))

OUT.write_text(
    """/* MLILY U 3.0, Mattresses template at laptop widths. GENERATED by tools/build-laptop-css.py: edit the tool, not the tablet block.
   992-1100 px uses the template's tablet layout under the desktop top bar; 1101-1299 px narrows the Mattress index. */

@media screen and (min-width: 992px) and (max-width: 1100px) {
__RULES__
}

/* The prototype's wider margins from 1024 px */
@media screen and (min-width: 1024px) and (max-width: 1100px) {
  .page-container { padding-left: 32px; padding-right: 32px; }
  .product-hero__inner { padding-left: 32px; padding-right: 32px; }
}

/* Narrower Mattress index, so the page keeps its room */
@media screen and (min-width: 1101px) and (max-width: 1299px) {
  .side-index { width: calc((100% - 328px) / 6 + 32px); }
  .page-panel { margin-left: calc((100% - 332px) / 6 + 56px); }
}
""".replace("__RULES__", "\n".join(rules)),
    encoding="utf8",
)
print("%d rules written to %s" % (len(rules), OUT))
